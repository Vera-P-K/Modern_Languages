// выбрана программа из задания 2
#include <iostream>
#include <fstream>
#include <iomanip>   // Для манипуляторов форматирования (setw, setprecision)
#include <string>

using namespace std;

int main() {
    string fname = "test.txt";
    
    // 1. Открываем файл в режиме чтения и записи одновременно
    fstream fs(fname, ios::in | ios::out | ios::trunc); 

    if (!fs.is_open()) {
        cerr << "Ошибка открытия!" << endl;
        return 1;
    }

    // --- МЕТОДЫ ИЗМЕНЕНИЯ СОСТОЯНИЯ ---

    // 2. Установка формата вывода (манипуляторы)
    // fixed — фиксированная запятая, setprecision(2) — два знака после запятой
    fs << fixed << setprecision(2) << 123.4567 << endl; 
    
    // 3. seekp (seek put) — перемещение указателя записи
    // Перемещаемся в начало файла (0 байт от начала ios::beg)
    fs.seekp(0, ios::beg); 
    fs << "999.99"; // Перезаписываем начало файла

    // 4. clear() — сброс флагов ошибок
    // Если мы дошли до конца файла, поток "заблокируется". clear() оживит его.
    fs.clear(); 

    // 5. seekg (seek get) — перемещение указателя чтения
    // Ставим "курсор" на 2-й символ от начала файла
    fs.seekg(2, ios::beg); 

    char c;
    fs >> c; // Считываем символ с позиции 2
    cout << "Символ на позиции 2: " << c << endl;

    // 6. Проверка состояний (флаги)
    if (fs.eof()) cout << "Достигнут конец файла" << endl; // eof() — конец файла
    if (fs.fail()) cout << "Ошибка типа данных" << endl;   // fail() — критическая ошибка
    if (fs.good()) cout << "Поток в порядке" << endl;      // good() — всё отлично

    // 7. flush() — принудительная запись из буфера на диск
    // Гарантирует, что данные не пропадут, если программа внезапно закроется
    fs.flush(); 

    fs.close(); // Закрываем поток
    return 0;
}
