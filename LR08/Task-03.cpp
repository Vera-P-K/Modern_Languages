//
#include <iostream> // Для cin, cout
#include <fstream>  // Для работы с файловыми потоками (ifstream, ofstream)
#include <string>   // Для работы со строками (ключ)
#include <vector>   // Для безопасного хранения данных

using namespace std; // Используем стандартное пространство имен

int main(int argc, char* argv[]) {
    // 1. Проверка наличия ключа в аргументах командной строки
    if (argc < 2) {
        cerr << "Использование: " << argv[0] << " <ключ>" << endl;
        return 1; // Выход с кодом ошибки
    }

    string key = argv[1]; // Сохраняем ключ в объект класса string
    if (key.empty()) return 1; // Защита от пустого ключа

    // 2. Открытие потоков в бинарном режиме (ios::binary)
    // ifstream — поток для чтения (input), ofstream — для записи (output)
    ifstream ifs("input.dat", ios::binary);
    ofstream ofs("output.dat", ios::binary);

    // 3. Проверка состояния потоков (метод is_open или просто проверка объекта)
    if (!ifs || !ofs) {
        cerr << "Ошибка: не удалось открыть файлы!" << endl;
        return 1;
    }

    char c;           // Буфер для одного байта
    size_t index = 0; // Индекс для циклического прохода по ключу

    // 4. Побайтовое чтение с помощью метода get()
    // Цикл продолжается, пока чтение успешно (не достигнут конец файла)
    while (ifs.get(c)) {
        // Применяем XOR (^) к байту файла и символу ключа
        // static_cast превращает char в число для корректного вычисления
        char encrypted = c ^ key[index % key.length()];
        
        // Запись зашифрованного байта в выходной поток
        ofs.put(encrypted);
        
        index++; // Сдвигаемся к следующему символу ключа
    }

    // 5. Завершение работы
    // Потоки закроются автоматически при выходе объекта из области видимости (деструктором),
    // но явное закрытие приветствуется.
    ifs.close();
    ofs.close();

    cout << "Файл успешно обработан. Результат: output.dat" << endl;

    return 0; // Успешное завершение
}
