#include <stdio.h>
#include <string.h>

// argc — количество аргументов, argv — массив строк (аргументов)
int main(int argc, char* argv[]) {
    // 1. Проверка, передал ли пользователь ключ (argv[1])
    if (argc < 2) {
        printf("Использование: document.doc <ключ>\n");
        return 1;
    }

    char* key = argv[1];       // Указатель на строку-ключ из параметров
    int keyLen = strlen(key);  // Узнаем длину ключа для циклического использования
    int keyIndex = 0;          // Индекс текущего символа ключа

    // 2. Открываем файлы в бинарном режиме ("rb", "wb"), а текстовый режим ("w", "r")
    // Это позволяет шифровать любые файлы, а не только текст
    FILE *in = fopen("input.dat", "rb");
    FILE *out = fopen("output.dat", "wb");

    if (!in || !out) {
        printf("Ошибка при открытии файлов!\n");
        return 1;
    }

    int c; // Переменная для хранения считанного байта (int, чтобы ловить EOF)
// (End of File — конец файла) — это специальная константа
    // 3. Читаем файл по одному байту до самого конца
    while ((c = fgetc(in)) != EOF) {
        // XOR (исключающее ИЛИ) текущего байта с символом ключа
        // Используется остаток от деления (%), чтобы ключ шел по кругу
        int encrypted = c ^ key[keyIndex % keyLen];
        
        fputc(encrypted, out); // Запись результата в файл
        keyIndex++;            // Сдвиг по ключу дальше
    }

    // 4. Закрываем файлы и освобождаем ресурсы
    fclose(in);
    fclose(out);

    printf("Итог в файле output.dat\n");
    return 0;
}
