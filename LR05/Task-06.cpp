#include <stdio.h>
#include <string.h>

// argc — количество аргументов, argv — массив строк-аргументов
int main(int argc, char* argv[]) {
    // 1. Проверяем, ввел ли пользователь все 3 нужных параметра
    if (argc < 4) {
        printf("Использование: %s <входной_файл> <выходной_файл> <ключ>\n", argv[0]);
        return 1;
    }

    // 2. Назначаем понятные имена для аргументов из командной строки
    char* inputName = argv[1];   // Имя файла, который читаем
    char* outputName = argv[2];  // Имя файла, в который пишем
    char* key = argv[3];         // Строка-ключ для XOR
    
    int keyLen = strlen(key);    // Определяем длину ключа для циклического сдвига
    int keyIndex = 0;            // Счетчик для прохода по символам ключа

    // 3. Открываем файлы в бинарном режиме ("rb", "wb") для точности байтов
    FILE *in = fopen(inputName, "rb");
    FILE *out = fopen(outputName, "wb");

    // Проверяем, удалось ли открыть/создать файлы
    if (in == NULL || out == NULL) {
        printf("Ошибка: не удалось открыть файлы. Проверьте пути.\n");
        if (in) fclose(in); // Если открылся только один, закрываем его
        return 1;
    }

    int c; // Переменная для хранения одного считанного байта

    // 4. Основной цикл: читаем файл по одному байту до конца (EOF)
    while ((c = fgetc(in)) != EOF) {
        // Применяем XOR (знак ^) между байтом файла и текущим символом ключа
        // Оператор % (остаток от деления) заставляет ключ повторяться по кругу
        int encrypted = c ^ key[keyIndex % keyLen];
        
        // Записываем результат (зашифрованный байт) в выходной файл
        fputc(encrypted, out);
        
        // Увеличиваем индекс ключа для следующего байта
        keyIndex++;
    }

    // 5. Закрываем потоки данных (сохраняем изменения на диск)
    fclose(in);
    fclose(out);

    printf("Файл '%s' обработан ключом и сохранен как '%s'.\n", inputName, outputName);

    return 0;
}
