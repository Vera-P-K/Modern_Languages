#include <stdio.h>

int main(void) { // Стандартный вход в программу
    char name[50], ch; // Массив для имени файла и переменная для текущего символа
    FILE *in; // Указатель на структуру файла

    printf("Файл: "); // Запрос имени файла
    scanf("%49s", name); // Считываем имя (ограничение 49 символов для безопасности)

    // Открываем файл и сразу проверяем результат. "r" — режим чтения (read)
    if ((in = fopen(name, "r")) == NULL) {
        return printf("Ошибка открытия %s\n", name), 1; // Вывод ошибки и выход при неудаче
    }

    // Читаем символ и проверяем, не конец ли это файла (EOF)
    while ((ch = getc(in)) != EOF) {
        putchar(ch); // Выводим считанный символ на экран
    }

    fclose(in); // Обязательно закрываем файл, чтобы освободить ресурсы системы
    return 0; // Успешное завершение
}
