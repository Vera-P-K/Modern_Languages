#include <stdio.h> // Подключение библиотеки стандартного ввода-вывода (для printf)

// Объявление макроса PR, который принимает аргумент x (указатель)
// #x — превращает имя переменной в строку
// %p — выводит адрес памяти в шестнадцатеричном виде
// %d — выводит целое число (разыменованное значение *x)
// (void*) — приведение к типу void* для безопасного вывода адреса через %p
#define PR(x) printf(#x "=%p, *" #x "=%d, &" #x "=%p\n", (void*)x, *x, (void*)&x)

int main(void) { // Главная функция программы, возвращает целое число (стандарт C++)
    
    // Объявление и инициализация массива из 3-х целых чисел
    int mas[] = {100, 200, 300}; 
    
    // Объявление двух указателей на целые числа
    int *ptr1, *ptr2;
    
    // Присваиваем ptr1 адрес начала массива (mas — это адрес первого элемента)
    ptr1 = mas;
    
    // Присваиваем ptr2 адрес третьего элемента массива (индекс 2)
    ptr2 = &mas[2];
    
    // Вывод состояния ptr1: его значения (адрес), значения по этому адресу (100) и адреса самого указателя
    PR(ptr1);
    
    // Инкремент указателя: ptr1 теперь указывает на следующий элемент (mas[1], т.е. 200)
    // Адрес увеличивается на sizeof(int) — обычно 4 байта
    ptr1++;
    
    // Вывод состояния ptr1 после сдвига (значение по адресу теперь 200)
    PR(ptr1);
    
    // Вывод состояния ptr2: указывает на mas[2] (значение 300)
    PR(ptr2);
    
    // Инкремент указателя ptr2: теперь он указывает на ячейку памяти СРАЗУ ЗА массивом
    ++ptr2;
    
    // Вычисление разности указателей. 
    // Результат — количество элементов между ними, а не байт.
    // %td — специальный спецификатор для типа ptrdiff_t (результат вычитания указателей)
    printf("ptr2-ptr1=%td\n", ptr2 - ptr1);
    
    return 0; // Завершение программы с кодом 0 (успешно)
}
