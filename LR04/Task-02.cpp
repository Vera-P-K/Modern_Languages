#include <iostream> // Подключение библиотеки для работы с консолью (cout, endl)

using namespace std; // Использование стандартного пространства имен (чтобы не писать std::)

// --- ТРИ СПОСОБА ОПРЕДЕЛЕНИЯ ДЛИНЫ ---

// 1. Способ через индекс массива
int dlina1(char* s) {
    int i = 0; // Счетчик символов
    while (s[i] != '\0') i++; // Пока не встретим символ конца строки '\0', увеличиваем индекс
    return i; // Возвращаем итоговое количество
}

// 2. Способ через перебор указателем
int dlina2(char* s) {
    int count = 0; // Счетчик
    while (*s) { // Пока значение, на которое указывает s, не равно 0 (то есть не '\0')
        count++; // Увеличиваем счетчик
        s++;     // Сдвигаем указатель на следующий байт (символ)
    }
    return count; // Возвращаем длину
}

// 3. Способ через адресную арифметику
int dlina3(char* s) {
    char* p = s; // Создаем временный указатель p, смотрящий в начало строки
    while (*p) p++; // Двигаем его до самого конца (до символа '\0')
    return p - s; // Вычитаем адрес начала из адреса конца — получаем количество элементов
}

// --- КОПИРОВАНИЕ, СРАВНЕНИЕ, КОНКАТЕНАЦИЯ ---

// Копирует строку из src в dest
void kopir(char* dest, char* src) {
    while (*src) {       // Пока в источнике есть символы
        *dest = *src;    // Копируем текущий символ из источника в приемник
        dest++;          // Сдвигаем приемник
        src++;           // Сдвигаем источник
    }
    *dest = '\0';        // В конце ПРИНУДИТЕЛЬНО ставим признак конца строки
}

// Сравнение строк (возвращает 0, если строки одинаковы)
int sravn(char* s1, char* s2) {
    // Пока символы равны и первая строка не закончилась
    while (*s1 && (*s1 == *s2)) {
        s1++; // Переходим к следующему символу
        s2++;
    }
    // Возвращаем разность последних несовпавших символов (0 если строки равны)
    return *(unsigned char*)s1 - *(unsigned char*)s2;
}

// Конкатенация (приклеивание src к концу dest)
void konkat(char* dest, char* src) {
    while (*dest) dest++; // 1. Находим конец первой строки (встаем на '\0')
    while (*src) {        // 2. Начинаем запись поверх '\0' символов из второй строки
        *dest = *src;
        dest++;
        src++;
    }
    *dest = '\0';         // 3. Завершаем новую длинную строку нулем
}

int main() {
    // Объявляем массивы. Для str1 выделяем 50 байт, чтобы в него влезла вторая строка
    char str1[50] = "qwerty"; 
    char str2[] = "12345";

    // Тестируем все три способа длины
    cout << "Dlina 1: " << dlina1(str1) << endl;
    cout << "Dlina 2: " << dlina1(str2) << endl;
    cout << "Dlina 3: " << dlina3(str1) << endl;

    // Сравниваем строки
    int res = sravn(str1, str2);
    cout << "Resultat sravneniya: " << (res == 0 ? "Ravny" : "Raznye") << endl;

    // Склеиваем строки (str1 станет "qwerty12345")
    konkat(str1, str2);
    cout << "Rezultat konkat: " << str1 << endl;

    // Копируем новую фразу в str1 (затирая старое значение)
    kopir(str1, "NewText");
    cout << "Rezultat kopir: " << str1 << endl;

    return 0; // Успешное завершение программы
}
