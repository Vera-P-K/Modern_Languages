#include <iostream>
#include <cstdlib> // Библиотека для malloc, calloc и free
#include <cstring> // Библиотека для strcpy

using namespace std;

int main() {
    int n = 3; // Количество строк в массиве
    int size = 50; // Максимальный размер каждой строки

    // 1. Создаем "фундамент" — массив указателей (динамический массив из n элементов char*)
    // malloc выделяет память под n указателей. sizeof(char*) — это размер одного адреса.
    char** mas = (char**)malloc(n * sizeof(char*));

    if (mas == NULL) return 1; // Проверка: удалось ли выделить память под массив

    // 2. Выделяем память под каждую строку отдельно
    for (int i = 0; i < n; i++) {
        // calloc(количество, размер) — выделяет память и сразу ЗАПОЛНЯЕТ ЕЕ НУЛЯМИ (\0)
        // Это безопаснее, так как строка сразу считается пустой и корректной.
        mas[i] = (char*)calloc(size, sizeof(char));
        
        if (mas[i] == NULL) return 1; // Проверка выделения памяти под конкретную строку
    }

    // 3. Заполняем строки данными
    strcpy(mas[0], "Строка один");
    strcpy(mas[1], "Строка два");
    strcpy(mas[2], "Строка три");

    // 4. Выводим результат на экран
    for (int i = 0; i < n; i++) {
        cout << "Mas[" << i << "]: " << mas[i] << endl;
    }

    // 5. ОСВОБОЖДЕНИЕ ПАМЯТИ (в обратном порядке)
    for (int i = 0; i < n; i++) {
        free(mas[i]); // Сначала удаляем каждую строку (внутренние блоки)
    }
    free(mas); // Затем удаляем сам массив указателей (внешний блок)

    return 0;
}
