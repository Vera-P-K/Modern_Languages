#include <iostream>

using namespace std;

class Stroka {
    char* str; // Указатель на массив символов в динамической памяти
    int size;  // Переменная для хранения выделенного размера

public:
    // 1. НОВЫЙ КОНСТРУКТОР: создает пустую строку заданного размера
    Stroka(int n) {
        size = n;               // Сохраняем размер
        str = new char[size];   // Выделяем n байт в "куче" (динамической памяти)
        str[0] = '\0';          // Инициализируем как пустую строку
    }

    // 2. Конструктор из обычной строки
    Stroka(const char* s) {
        size = 80;              // Задаем стандартный размер (или strlen(s)+1)
        str = new char[size];   // Выделяем память
        int i = 0;
        while (s[i] != '\0' && i < size - 1) { // Копируем данные вручную
            str[i] = s[i];
            i++;
        }
        str[i] = '\0';
    }

    // 3. ДЕСТРУКТОР: обязателен при использовании new
    ~Stroka() {
        delete[] str; // Освобождаем память, которую занял объект
    }

    // Метод вывода
    void vyvod() {
        if (str) cout << str;
    }
};

int main() {
    // Создаем экземпляр класса, выделяя под него 100 байт динамической памяти
    Stroka s_dynamic(100); 
    
    cout << "Файл создан" << endl;
    s_dynamic.vyvod();

    return 0;
}
